from __future__ import annotations
from typing import Protocol, runtime_checkable
import numpy as np
import pandas as pd

@runtime_checkable
class MetaEntryEstimator(Protocol):
    """Binary classifier: P(trade hits target before stop)."""
    def fit(self, X: pd.DataFrame, y: pd.Series, sample_weight: np.ndarray | None = None) -> None: ...
    def predict_proba(self, X: pd.DataFrame) -> np.ndarray: ...
    def feature_importances(self) -> np.ndarray: ...
    def get_params(self) -> dict: ...

@runtime_checkable
class MetaExecEstimator(Protocol):
    """Multi-task: kelly_fraction regression + pair_index classification."""
    def fit(self, X: pd.DataFrame, y_kelly: pd.Series, y_pair: pd.Series, sample_weight: np.ndarray | None = None) -> None: ...
    def predict(self, X: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]: ...
    def feature_importances(self) -> np.ndarray: ...
    def get_params(self) -> dict: ...
